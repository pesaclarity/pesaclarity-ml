"""The examples page: synthetic messages the reader trains on, with every field marked.

``akili reader-examples`` writes ``docs/READER-EXAMPLES.md``; a test fails if the page drifts
from the generator. Everything on it is invented.
"""

from __future__ import annotations

from pathlib import Path

from akili.reader.synthetic import FIELD_LABELS, LAYOUTS, Field, Message, generate
from akili.reader.tokens import tokenise

PER_LAYOUT = 3
NOTICES = 6
_SEED = 11
_POOL = 6000


def _layout(style: str) -> str | None:
    parts = style.split("|")
    return parts[5] if len(parts) > 6 else None


def _fields(m: Message) -> str:
    """Each labelled span as ``field: text``, in message order."""
    out: list[str] = []
    tokens = tokenise(m.text)
    i = 0
    while i < len(tokens):
        label = m.fields[i]
        if label == Field.OTHER:
            i += 1
            continue
        j = i
        while j + 1 < len(tokens) and m.fields[j + 1] == label:
            j += 1
        out.append(f"{FIELD_LABELS[label]}: `{m.text[tokens[i].start : tokens[j].end]}`")
        i = j + 1
    return " · ".join(out) or "none"


def _entry(m: Message) -> list[str]:
    kind = m.kind.name.lower().replace("_", " ")
    return ["```text", m.text, "```", "", f"{kind} · {_fields(m)}", ""]


def render() -> str:
    messages = generate(_POOL, seed=_SEED)
    lines = [
        "# Reader examples",
        "",
        "Synthetic messages the message reader trains on, with the fields it learns to find. "
        "Generated by `akili reader-examples` from `akili.reader.synthetic`; do not edit. "
        "Institutions, people, numbers and links are invented.",
        "",
        "Evaluation holds each layout out in turn, so its scores are for wording the model "
        "never saw (see the README).",
        "",
    ]
    for layout in LAYOUTS:
        picked = [m for m in messages if _layout(m.style) == layout][:PER_LAYOUT]
        lines += [f"## {layout}", ""]
        for m in picked:
            lines += _entry(m)
    lines += ["## Not transactions", ""]
    for m in [m for m in messages if _layout(m.style) is None][:NOTICES]:
        lines += _entry(m)
    return "\n".join(lines).rstrip() + "\n"


def default_path() -> Path:
    return Path(__file__).resolve().parents[3] / "docs" / "READER-EXAMPLES.md"
